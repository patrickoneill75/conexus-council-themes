"""Cut a running document (one file, many meetings) into one piece per meeting.

The onboarding notes are one Word file that staff add to as calls happen: Copilot summaries,
each under a "Company:" line, then notes typed by hand, also under company lines, with Word
headings here and there. The file and the way it grows cannot change, so this module handles
the mess in two layers.

Layer 1, in code, keeps only the cuts it is sure of:
  - a Copilot tag ("Generated by AI...") with a company line right above it;
  - a Heading 1;
  - a short line that names a partner on the roster ("Grote:", "Honda Kickoff:").
A Copilot tag with no company line right above it is not a new meeting: it belongs to the
company before it (the Overton prep notes, then Overton's Copilot summary).

Layer 2 sends a piece Claude only when layer 1 left it long, unlabelled, or labelled with a
company its text is not about. That call returns where each meeting starts (its first words,
checked against the text in code), the company, and a meeting date if the text states one. It
records no statements. The answer is stored under a key made of the text, so it is paid for once
and asked again only for new or changed text.

Dates: a date written at the top of the meeting (its heading line or the two lines after it);
otherwise, for a meeting that was already in the file when it was first read, the date an admin
entered in the meeting dates list, or no date at all; otherwise the date the meeting first
appeared. Never the date the whole file was uploaded.

A meeting whose text is a copy of an earlier one (GPC's section is Sacoma's, word for word) is
flagged and not read, so the copy's statements are not credited to a second company.
"""
