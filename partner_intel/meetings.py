def _safe(value) -> str:
    text = str(value if value is not None else "")
    return "'" + text if text[:1] in ("=", "+", "-", "@", "\t", "\r") else text


def list_rows(file_label: str, meetings: list[Meeting], resolver: Resolver, dated: dict[str, tuple[str, str]]) -> list[dict]:
    names = {m.id: m.company for m in meetings}
    by_id = resolver.roster.by_id()
    rows = []
    for n, m in enumerate(meetings, 1):
        hit = resolver.company(_strip_dates(m.company), guess=True) if m.company else None
        on_list = by_id[hit.company_id]["name"] if hit and hit.ok else ("several partners match" if hit and hit.method == "ambiguous" else "no")
        when, source = dated.get(m.id, ("", ""))
        rows.append({"MeetingID": m.id, "File": file_label, "Order": n, "Company": m.company or "(none)",
                     "OnPartnerList": on_list, "HowFound": m.how, "Words": m.words, "FirstWords": _first_words(m.text),
                     "Date": when or "unknown", "DateSource": source,
                     "DuplicateOf": names.get(m.duplicate_of, "") if m.duplicate_of else "",
                     "SentToClaude": m.sent, "Note": m.note})
    return rows


def to_csv(rows: list[dict], columns: list[str]) -> str:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\r\n")
    writer.writerow(columns)
    for r in rows:
        writer.writerow([_safe(r.get(c, "")) for c in columns])
    return "﻿" + out.getvalue()


def dates_seed(rows: list[dict]) -> list[dict]:
    """The rows an admin fills in: meetings with no date of their own that are not copies."""
    return [{"MeetingID": r["MeetingID"], "File": r["File"], "Company": r["Company"], "FirstWords": r["FirstWords"],
             "Date": ""} for r in rows if r["DateSource"] == "unknown" and not r["DuplicateOf"]]


